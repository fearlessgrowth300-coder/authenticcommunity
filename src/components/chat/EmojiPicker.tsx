interface EmojiPickerProps {
  onSelect: (emoji: string) => void;
  onClose: () => void;
}

const EmojiPicker = ({ onSelect, onClose }: EmojiPickerProps) => {
  const [activeCategory, setActiveCategory] = useState("Smileys");
  const categories = Object.keys(EMOJI_CATEGORIES);

  return (
    <div className="bg-card border-t border-border">
      {/* Category tabs */}
      <div className="flex overflow-x-auto no-scrollbar border-b border-border/50 px-2">
        {categories.map((cat) => (
          <button
            key={cat}
            onClick={() => setActiveCategory(cat)}
            className={cn(
              "px-3 py-2 text-xs whitespace-nowrap transition-colors",
              activeCategory === cat
                ? "text-primary border-b-2 border-primary font-medium"
                : "text-muted-foreground"
            )}
          >
            {cat}
          </button>
        ))}
      </div>
      {/* Emoji grid */}
      <div className="h-48 overflow-y-auto p-2">
        <div className="grid grid-cols-8 gap-1">
          {EMOJI_CATEGORIES[activeCategory as keyof typeof EMOJI_CATEGORIES].map((emoji, i) => (
            <button
              key={i}
              onClick={() => { onSelect(emoji); onClose(); }}
              className="h-9 w-9 flex items-center justify-center text-xl hover:bg-muted rounded-lg transition-colors"
            >
              {emoji}
            </button>
          ))}
        </div>
      </div>
    </div>
  );
};

export default EmojiPicker;
